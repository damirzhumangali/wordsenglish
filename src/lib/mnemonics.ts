/**
 * Returns a mnemonic memory hook for a given word.
 * Priority:
 * 1. word.mnemonic (custom/overridden)
 * 2. MNEMONIC_DICTIONARY lookup by lowercased English word
 * 3. Auto-generated phonetic hint based on word syllables
 */
export function getWordMnemonic(word: Word): string | undefined {
  if (word.mnemonic && word.mnemonic.trim().length > 0) {
    return word.mnemonic;
  }

  const key = word.word.toLowerCase().trim();
  if (MNEMONIC_DICTIONARY[key]) {
    return MNEMONIC_DICTIONARY[key];
  }

  return undefined;
}
